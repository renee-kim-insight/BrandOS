// The palette lock: which colours and fonts an app may use, and the checks that enforce it.
//
// Rule: any colour with real chroma (anything that is not black, white or a grey) must belong to a brand
// colour's hue family: the same hue within a small tolerance, at any lightness or strength. That allows
// tints, shades, glass over brand colours and gradients between brand colours, and nothing else.
import { hex, isNeutral, oklch } from "./color.mjs"

export const NEUTRAL_CHROMA = 0.04
export const HUE_TOLERANCE = 14

const GENERIC_FONTS = /^(rockwell|georgia|ui-sans-serif|ui-serif|ui-monospace|system-ui|-apple-system|blinkmacsystemfont|sans-serif|serif|monospace|cursive|fantasy|emoji|math|inherit|initial|unset|revert|var\(.*|segoe ui|helvetica|helvetica neue|arial|apple color emoji|segoe ui emoji|segoe ui symbol|noto color emoji|sfmono-regular|menlo|monaco|consolas|courier new|roboto mono|liberation mono)$/i

/** Build palette.json from a brand and its generated theme. */
export function buildPalette(brand, theme) {
  const families = []
  const add = (role, value) => {
    if (!value) return
    const c = oklch(value)
    if (isNeutral(c) || c.c < NEUTRAL_CHROMA) return
    if (families.some((f) => Math.min(Math.abs(f.hue - c.h), 360 - Math.abs(f.hue - c.h)) < 1)) return
    families.push({ role, hex: hex(c), hue: Math.round(c.h * 10) / 10 })
  }
  const col = brand.colors
  add("primary", col.primary)
  add("secondary", col.secondary)
  for (const a of col.accents ?? []) add("accent", a)
  add("danger", col.danger)
  for (const [mode, t] of Object.entries(theme.modes)) {
    add(`primary (${mode})`, t.primary)
    add(`ring (${mode})`, t.ring)
    add(`destructive (${mode})`, t.destructive)
  }
  const fonts = {}
  for (const [k, f] of Object.entries(brand.fonts ?? {})) {
    // A display font is only on brand when the brand opted in to it for headings.
    if (!f || (k === "display" && brand.typography?.headings !== "display")) continue
    fonts[k] = [f.family, f.fallback].filter(Boolean)
  }
  if (!fonts.mono) fonts.mono = ["Geist Mono"]
  return {
    $comment: "Generated by BrandOS. Every coloured (non-grey) value in the app must share a hue with one of these families. Fonts must be one of these families or a generic fallback.",
    brand: brand.name,
    rules: { neutralChroma: NEUTRAL_CHROMA, hueTolerance: HUE_TOLERANCE },
    families,
    fonts,
  }
}

/** Is this colour allowed? Returns { ok, nearest } where nearest is the closest brand family. */
export function checkColour(value, palette) {
  let c
  try {
    c = oklch(value)
  } catch {
    return { ok: true }
  }
  if (c.alpha === 0) return { ok: true }
  const neutral = palette.rules?.neutralChroma ?? NEUTRAL_CHROMA
  if (c.c < neutral) return { ok: true }
  // Pale tints and glass blends have unstable hue (a little chroma, mixed with a warm or cool neutral),
  // so the tolerance widens as chroma drops. Strong colours must match closely.
  const tol = (palette.rules?.hueTolerance ?? HUE_TOLERANCE) + Math.max(0, 0.12 - c.c) * 150
  let nearest = null
  let best = 999
  for (const f of palette.families) {
    const d = Math.min(Math.abs(c.h - f.hue), 360 - Math.abs(c.h - f.hue))
    if (d < best) [best, nearest] = [d, f]
  }
  return { ok: best <= tol, nearest, hex: hex(c), hueGap: Math.round(best) }
}

/** Is this font-family value allowed? */
export function checkFont(value, palette) {
  const allowed = new Set(Object.values(palette.fonts ?? {}).flat().map((f) => f.toLowerCase()))
  const bad = []
  for (const part of value.split(",")) {
    const name = part.trim().replace(/^["']|["']$/g, "").trim()
    if (!name || GENERIC_FONTS.test(name) || allowed.has(name.toLowerCase()) || /^var\(--/.test(name)) continue
    bad.push(name)
  }
  return { ok: bad.length === 0, bad }
}

const NAMED = "aqua|aquamarine|blue|blueviolet|brown|burlywood|cadetblue|chartreuse|chocolate|coral|cornflowerblue|crimson|cyan|darkblue|darkcyan|darkgoldenrod|darkgreen|darkkhaki|darkmagenta|darkolivegreen|darkorange|darkorchid|darkred|darksalmon|darkseagreen|darkslateblue|darkturquoise|darkviolet|deeppink|deepskyblue|dodgerblue|firebrick|forestgreen|fuchsia|gold|goldenrod|green|greenyellow|hotpink|indianred|indigo|khaki|lawngreen|lightblue|lightcoral|lightgreen|lightpink|lightsalmon|lightseagreen|lightskyblue|lime|limegreen|magenta|maroon|mediumblue|mediumorchid|mediumpurple|mediumseagreen|mediumslateblue|mediumspringgreen|mediumturquoise|mediumvioletred|midnightblue|navy|olive|olivedrab|orange|orangered|orchid|palegreen|paleturquoise|palevioletred|peru|pink|plum|powderblue|purple|rebeccapurple|red|royalblue|saddlebrown|salmon|sandybrown|seagreen|sienna|skyblue|slateblue|springgreen|steelblue|tan|teal|tomato|turquoise|violet|yellow|yellowgreen"
const COLOUR_RE = new RegExp(String.raw`#[0-9a-fA-F]{3,8}\b(?![\w-])|\b(?:rgba?|hsla?|oklch|oklab|lab|lch|hwb)\([^)]*\)|(?<=[:\s,(])(?:${NAMED})\b(?=\s*[;,)}\s"'])`, "g")
const TW_RE = /\b(?:bg|text|border|ring|fill|stroke|from|to|via|outline|divide|placeholder|decoration|accent|caret|shadow)-(red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose)-\d{2,3}\b/g
const FONT_RE = /font-family\s*:\s*([^;}{]+)|fontFamily\s*:\s*["'`]([^"'`]+)["'`]/g

/** Scan source text. Returns [{ line, kind, value, detail }] for everything outside the palette. */
export function scanSource(text, palette) {
  const out = []
  const lines = text.split("\n")
  lines.forEach((line, i) => {
    if (/^\s*(\/\/|\*|\/\*)/.test(line) || /url\(\s*["']?data:/.test(line)) return
    for (const m of line.matchAll(COLOUR_RE)) {
      if (/^#[0-9]+$/.test(m[0]) && (m[0].length === 5 || m[0].length === 9)) continue // "#1042" is a number, not a colour
      const r = checkColour(m[0], palette)
      if (!r.ok) out.push({ line: i + 1, kind: "colour", value: m[0], detail: `not a brand hue (nearest brand colour ${r.nearest?.hex ?? "none"}, ${r.hueGap}° away)` })
    }
    for (const m of line.matchAll(TW_RE)) out.push({ line: i + 1, kind: "colour", value: m[0], detail: "stock palette class; use a theme token" })
    for (const m of line.matchAll(FONT_RE)) {
      const r = checkFont(m[1] ?? m[2], palette)
      if (!r.ok) out.push({ line: i + 1, kind: "font", value: r.bad.join(", "), detail: "not a brand font; use var(--font-sans) or var(--font-display)" })
    }
  })
  return out
}
